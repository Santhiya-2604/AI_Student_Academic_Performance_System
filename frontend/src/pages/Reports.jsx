import { useState } from "react";
import { jsPDF } from "jspdf";
import {
  FileText,
  Search,
  Download,
  RefreshCw,
  ArrowLeft,
} from "lucide-react";
import { useNavigate } from "react-router-dom";

function Reports() {
  const navigate = useNavigate();

  const [studentId, setStudentId] = useState("");
  const [reportType, setReportType] = useState("dataset");
  const [student, setStudent] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");

  const getValue = (obj, keys, fallback = "N/A") => {
    for (const key of keys) {
      if (
        obj &&
        obj[key] !== undefined &&
        obj[key] !== null &&
        obj[key] !== ""
      ) {
        return obj[key];
      }
    }

    return fallback;
  };

  const fetchReportStudent = async () => {
    const id = studentId.trim();

    if (!id) {
      setError("Please enter a Student ID.");
      return;
    }

    try {
      setLoading(true);
      setError("");
      setStudent(null);

      const endpoint =
        reportType === "dataset"
          ? `http://127.0.0.1:5000/api/dashboard/student/${encodeURIComponent(
              id
            )}`
          : `http://127.0.0.1:5000/api/students/${encodeURIComponent(id)}`;

      const response = await fetch(endpoint);
      const data = await response.json();

      if (!response.ok || !data.success) {
        throw new Error(data.message || "Student not found.");
      }

      setStudent(data.student || data);
    } catch (err) {
      console.error("Report Error:", err);

      setError(
        err.message || "Unable to load student information."
      );
    } finally {
      setLoading(false);
    }
  };

  const buildReportText = () => {
    if (!student) return "";

    const id = getValue(
      student,
      ["student_id", "studentid", "id"],
      studentId
    );

    const name = getValue(student, [
      "name",
      "student_name",
    ]);

    const department = getValue(student, [
      "department",
    ]);

    const semester = getValue(student, [
      "semester",
    ]);

    const attendance = getValue(student, [
      "attendance_percentage",
      "attendance",
    ]);

    const overall = getValue(student, [
      "overall_performance_percentage",
      "overall_percentage",
      "overall_performance",
      "overall_score",
    ]);

    const category = getValue(student, [
      "performance_category",
      "category",
    ]);

    const risk = getValue(student, [
      "risk_status",
      "risk",
      "risk_level",
    ]);

    const trend = getValue(student, [
      "performance_trend",
      "trend",
    ]);

    const previous = getValue(student, [
      "previous_semester_percentage",
      "previous_percentage",
    ]);

    const studyHours = getValue(student, [
      "study_hours_per_day",
      "study_hours",
    ]);

    const backlog = getValue(student, [
      "backlog_count",
      "backlogs",
    ]);

    const subjectColumns = [
      ["Python", "python_marks"],
      ["Data Science", "data_science_marks"],
      ["DBMS", "dbms_marks"],
      ["Statistics", "statistics_marks"],
      ["Machine Learning", "machine_learning_marks"],
    ];

    let subjectText = "";

    subjectColumns.forEach(([label, key]) => {
      if (
        student[key] !== undefined &&
        student[key] !== null &&
        student[key] !== ""
      ) {
        subjectText += `${label}: ${student[key]}\n`;
      }
    });

    return `
AI STUDENT ACADEMIC PERFORMANCE SYSTEM
========================================

ACADEMIC PERFORMANCE REPORT

Report Type: ${
      reportType === "dataset"
        ? "Dataset Student"
        : "Admin-Added / Registered Student"
    }

----------------------------------------
STUDENT DETAILS
----------------------------------------

Student ID      : ${id}
Name            : ${name}
Department      : ${department}
Semester        : ${semester}

----------------------------------------
ACADEMIC PERFORMANCE
----------------------------------------

Attendance      : ${attendance}
Overall Score   : ${overall}
Category        : ${category}
Previous Score  : ${previous}
Study Hours     : ${studyHours}
Backlogs        : ${backlog}

----------------------------------------
PERFORMANCE TREND
----------------------------------------

Trend           : ${trend}

----------------------------------------
SUBJECT PERFORMANCE
----------------------------------------

${subjectText || "Subject marks not available."}

----------------------------------------
REPORT SUMMARY
----------------------------------------

This report provides a summary of the available
academic information for the selected student.

Risk Status     : ${risk}

Generated By    : Academic AI Performance System

========================================
`;
  };

  const downloadReport = () => {
    if (!student) return;

    const reportText = buildReportText();

    const doc = new jsPDF();

    const pageWidth = doc.internal.pageSize.getWidth();
    const pageHeight = doc.internal.pageSize.getHeight();

    const margin = 18;
    const maxWidth = pageWidth - margin * 2;
    const lineHeight = 6;

    let y = 20;

    const addText = (
      text,
      fontSize = 10,
      bold = false
    ) => {
      doc.setFont(
        "helvetica",
        bold ? "bold" : "normal"
      );

      doc.setFontSize(fontSize);

      const lines = doc.splitTextToSize(
        String(text),
        maxWidth
      );

      lines.forEach((line) => {
        if (y > pageHeight - 20) {
          doc.addPage();
          y = 20;
        }

        doc.text(line, margin, y);
        y += lineHeight;
      });
    };

    doc.setTextColor(16, 75, 77);

    addText(
      "AI STUDENT ACADEMIC PERFORMANCE SYSTEM",
      16,
      true
    );

    y += 3;

    addText(
      reportType === "dataset"
        ? "Dataset Student Performance Report"
        : "Admin-Added / Registered Student Performance Report",
      14,
      true
    );

    y += 5;

    doc.setTextColor(0, 0, 0);

    reportText.split("\n").forEach((line) => {
      const trimmedLine = line.trim();

      if (!trimmedLine) {
        y += 3;
        return;
      }

      const isSeparator =
        /^=+$|^-+$/.test(trimmedLine);

      if (isSeparator) {
        if (y > pageHeight - 20) {
          doc.addPage();
          y = 20;
        }

        doc.setDrawColor(190, 205, 205);

        doc.line(
          margin,
          y - 2,
          pageWidth - margin,
          y - 2
        );

        y += 3;
        return;
      }

      const isHeading = [
        "AI STUDENT ACADEMIC PERFORMANCE SYSTEM",
        "ACADEMIC PERFORMANCE REPORT",
        "STUDENT DETAILS",
        "ACADEMIC PERFORMANCE",
        "PERFORMANCE TREND",
        "SUBJECT PERFORMANCE",
        "REPORT SUMMARY",
      ].includes(trimmedLine);

      addText(
        trimmedLine,
        isHeading ? 11 : 10,
        isHeading
      );
    });

    const safeId = String(
      studentId.trim() || "student"
    ).replace(/[<>:"/\\|?*]+/g, "_");

    doc.save(
      `${safeId}_${reportType}_performance_report.pdf`
    );
  };

  const clearReport = () => {
    setStudentId("");
    setStudent(null);
    setError("");
  };

  return (
    <div
      style={{
        minHeight: "100vh",
        background: "#f6fbfb",
        padding: "30px",
        color: "#102f5b",
      }}
    >
      <div
        style={{
          maxWidth: "1150px",
          margin: "0 auto",
        }}
      >
        {/* HEADER */}

        <div
          style={{
            display: "flex",
            justifyContent: "space-between",
            alignItems: "center",
            gap: "20px",
            flexWrap: "wrap",
            marginBottom: "28px",
          }}
        >
          <div>
            <div
              style={{
                display: "flex",
                alignItems: "center",
                gap: "12px",
              }}
            >
              <FileText
                size={30}
                color="#0b8985"
              />

              <h1
                style={{
                  margin: 0,
                  fontSize: "30px",
                }}
              >
                Academic Reports
              </h1>
            </div>

            <p
              style={{
                color: "#64748b",
              }}
            >
              Generate and download student academic
              performance reports.
            </p>
          </div>

          <button
            onClick={() => navigate("/admin")}
            style={{
              background: "white",
              border: "1px solid #d5e5e5",
              padding: "10px 16px",
              borderRadius: "10px",
              cursor: "pointer",
              display: "flex",
              alignItems: "center",
              gap: "8px",
            }}
          >
            <ArrowLeft size={17} />
            Dashboard
          </button>
        </div>

        {/* REPORT TYPE */}

        <div
          style={{
            background: "white",
            border: "1px solid #dceaea",
            borderRadius: "16px",
            padding: "24px",
            marginBottom: "20px",
          }}
        >
          <h2
            style={{
              marginTop: 0,
            }}
          >
            Select Report Type
          </h2>

          <div
            style={{
              display: "flex",
              gap: "12px",
              flexWrap: "wrap",
            }}
          >
            <button
              onClick={() => {
                setReportType("dataset");
                setStudent(null);
                setError("");
              }}
              style={{
                padding: "13px 18px",
                borderRadius: "10px",
                border:
                  reportType === "dataset"
                    ? "2px solid #0b8985"
                    : "1px solid #d5e5e5",
                background:
                  reportType === "dataset"
                    ? "#e8f8f7"
                    : "white",
                color: "#104b4d",
                cursor: "pointer",
                fontWeight: 600,
              }}
            >
              Dataset Student
            </button>

            <button
              onClick={() => {
                setReportType("registered");
                setStudent(null);
                setError("");
              }}
              style={{
                padding: "13px 18px",
                borderRadius: "10px",
                border:
                  reportType === "registered"
                    ? "2px solid #0b8985"
                    : "1px solid #d5e5e5",
                background:
                  reportType === "registered"
                    ? "#e8f8f7"
                    : "white",
                color: "#104b4d",
                cursor: "pointer",
                fontWeight: 600,
              }}
            >
              Admin-Added Student
            </button>
          </div>
        </div>

        {/* SEARCH */}

        <div
          style={{
            background: "white",
            border: "1px solid #dceaea",
            borderRadius: "16px",
            padding: "24px",
            marginBottom: "20px",
          }}
        >
          <h2
            style={{
              marginTop: 0,
            }}
          >
            Generate Report
          </h2>

          <div
            style={{
              display: "flex",
              gap: "12px",
              flexWrap: "wrap",
            }}
          >
            <input
              value={studentId}
              onChange={(e) =>
                setStudentId(e.target.value)
              }
              onKeyDown={(e) => {
                if (e.key === "Enter") {
                  fetchReportStudent();
                }
              }}
              placeholder="Enter Student ID"
              style={{
                flex: 1,
                minWidth: "250px",
                padding: "13px 15px",
                border: "1px solid #cbdede",
                borderRadius: "10px",
                fontSize: "15px",
                outline: "none",
              }}
            />

            <button
              onClick={fetchReportStudent}
              disabled={loading}
              style={{
                background: "#0b8985",
                color: "white",
                border: "none",
                borderRadius: "10px",
                padding: "12px 20px",
                cursor: "pointer",
                display: "flex",
                alignItems: "center",
                gap: "8px",
              }}
            >
              {loading ? (
                <RefreshCw size={17} />
              ) : (
                <Search size={17} />
              )}

              {loading
                ? "Loading..."
                : "Generate Report"}
            </button>

            <button
              onClick={clearReport}
              style={{
                background: "#eef7f7",
                border: "none",
                borderRadius: "10px",
                padding: "12px 18px",
                cursor: "pointer",
              }}
            >
              Clear
            </button>
          </div>

          {error && (
            <div
              style={{
                marginTop: "15px",
                background: "#fff1f2",
                color: "#be123c",
                padding: "12px",
                borderRadius: "10px",
              }}
            >
              {error}
            </div>
          )}
        </div>

        {/* REPORT PREVIEW */}

        {student && (
          <div
            style={{
              background: "white",
              border: "1px solid #dceaea",
              borderRadius: "16px",
              padding: "26px",
            }}
          >
            <div
              style={{
                display: "flex",
                justifyContent: "space-between",
                alignItems: "center",
                gap: "15px",
                flexWrap: "wrap",
                marginBottom: "22px",
              }}
            >
              <div>
                <h2
                  style={{
                    margin: 0,
                  }}
                >
                  Report Preview
                </h2>

                <p
                  style={{
                    color: "#64748b",
                  }}
                >
                  {reportType === "dataset"
                    ? "Dataset Student"
                    : "Admin-Added / Registered Student"}
                </p>
              </div>

              <button
                onClick={downloadReport}
                style={{
                  background: "#0b8985",
                  color: "white",
                  border: "none",
                  borderRadius: "10px",
                  padding: "12px 18px",
                  cursor: "pointer",
                  display: "flex",
                  alignItems: "center",
                  gap: "8px",
                }}
              >
                <Download size={18} />
                Download Report
              </button>
            </div>

            <div
              style={{
                display: "grid",
                gridTemplateColumns:
                  "repeat(auto-fit,minmax(180px,1fr))",
                gap: "14px",
              }}
            >
              {[
                [
                  "Student ID",
                  getValue(
                    student,
                    [
                      "student_id",
                      "studentid",
                      "id",
                    ],
                    studentId
                  ),
                ],
                [
                  "Name",
                  getValue(student, [
                    "name",
                    "student_name",
                  ]),
                ],
                [
                  "Department",
                  getValue(student, [
                    "department",
                  ]),
                ],
                [
                  "Semester",
                  getValue(student, [
                    "semester",
                  ]),
                ],
                [
                  "Overall Performance",
                  getValue(student, [
                    "overall_performance_percentage",
                    "overall_percentage",
                    "overall_performance",
                  ]),
                ],
                [
                  "Attendance",
                  getValue(student, [
                    "attendance_percentage",
                    "attendance",
                  ]),
                ],
                [
                  "Risk Status",
                  getValue(student, [
                    "risk_status",
                    "risk",
                  ]),
                ],
                [
                  "Performance Trend",
                  getValue(student, [
                    "performance_trend",
                    "trend",
                  ]),
                ],
              ].map(([label, value]) => (
                <div
                  key={label}
                  style={{
                    padding: "18px",
                    background: "#f8fbfb",
                    borderRadius: "12px",
                  }}
                >
                  <small>{label}</small>

                  <strong
                    style={{
                      display: "block",
                      marginTop: "7px",
                      fontSize: "17px",
                    }}
                  >
                    {value}
                  </strong>
                </div>
              ))}
            </div>
          </div>
        )}
      </div>
    </div>
  );
}

export default Reports;